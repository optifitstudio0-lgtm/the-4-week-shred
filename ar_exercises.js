// "30s" -> "30 ث" ، "12 reps" -> "12 عدة" ، "24 Mins" -> "24 دقيقة"
export const durationAr = (txt) => {
  if (!txt) return '';
  const s = String(txt).trim();
  let m = s.match(/^(\d+)\s*s$/i);
  if (m) return `${m[1]} ث`;
  m = s.match(/^(\d+)\s*reps?$/i);
  if (m) return `${m[1]} عدة`;
  m = s.match(/^(\d+)\s*mins?$/i);
  if (m) return `${m[1]} دقيقة`;
  const map = { 'Recover': 'استشفاء', 'Relax & Recover': 'استرخي واستشفي', 'YOU MADE IT! 🎉': 'وصلت! 🎉' };
  return map[s] || s;
};
